#!/usr/bin/env bash
# Issue #793: PR 本文に `Closes #N`（または「対応する Issue は無い」の明示）を書かせる。
#
# なぜ要るか（実測 2026-09-13、`gh pr list --state merged --limit 300` の本文を
# board-audit.sh と同じ正規表現に掛けた）:
#   **マージ済み PR 300 件のうち閉じる語があるのは 151 件。直近 50 件では 有 28 / 無 22（44% が無い）。**
#   #783 で作った `scripts/po/board-audit.sh` は「`Closes #N` を含む PR が MERGED なのに
#   Issue が OPEN」を見る道具だが、**本丸 3 件のうち検出できたのは 1 件だけだった**
#   （#770→#763 と #776→#771 は閉じる語を一度も書いていない）。
#   **道具の射程が半分なのは、道具が緩すぎるからではなく、PR の側が書いていないから。**
#   **語を緩めて「本文に #N が出るだけ」を拾うのは間違い**（#569。#763 の検索には
#   無関係な PR #450/#698/#461 が引っかかった）。だから直すのは PR の側。
#
#   scripts/ci/pr-closes.sh <body-file>    PR 本文の入ったファイル（`-` で標準入力）
#     exit 0 — `Closes #N` がある、または「Issue 無し」の宣言がある
#     exit 1 — どちらも無い（**本丸**）
#     exit 2 — 使い方 / 本文を読めない
#     exit 3 — board-audit.sh から規則を取り出せない（**規則が読めないなら「合格」とは言わない**）
#
# ── 規則は board-audit.sh から実行時に取り出す（コピーしない）─────────────────────────────
#   **2 か所に同じ正規表現を書くと、片方だけ直したときに「CI は通るのに監査は拾わない」が起きる。**
#   #793 の指示は「board-audit.sh と同じ規則にすること」。**同じ**を一番強く保証するのは、
#   2 つ目の写しを作らないこと——だからこの検査は board-audit.sh の
#   `CLOSING_RE=...` の行を読んで、その値をそのまま使う。
#   board-audit.sh は **#783 でマージしたばかりなので変更しない**（#793 の指示）。
#   取り出せなかったら exit 3 で落ちる。**自前の規則に黙って退避しない**——
#   退避した時点で写しが 2 つになり、この設計が守ろうとしたものが消える。
#
# ── 「対応する Issue が無い PR」の逃げ道 ────────────────────────────────────────────────
#   **実在する。** PO 自身が 2026-09-13 に 3 本出している（#788 作業合意の更新 /
#   #789・#779 スプリント文書の更新）。**これらを機械的に赤くすると
#   「赤いのが普通」になって誰も見なくなる**——**#790 が扱っているのはまさにその状態
#   （6 日連続で赤い）**。だから明示的に書ける逃げ道を用意する。
#
#   綴り: **`Closes なし` に続けて括弧書きの理由**（例: `Closes なし（作業合意の更新）`）。
#   **この綴りを選んだ理由**（推測ではなく実測）:
#     · **すでに使われている。** 上の 300 件を `grep -ci 'Closes なし'` に掛けると **2 件**——
#       PR #788「Closes なし（作業合意の更新。対応する Issue は無い）」と
#       PR #789「Closes なし（スプリント文書の更新）」。**PO が自分で書き始めた形をそのまま採る。**
#       新しい綴りを発明すると、**すでに正しく書いている 2 本が明日から赤くなる。**
#     · **`Closes` で始まるので、`Closes #N` と同じ場所・同じ語で読める**（本文の末尾 1 行）。
#     · **理由が必須。** `Closes なし` だけでは通さない——**何も書かずに通せるなら今と同じ**（#793）。
#       理由は括弧の中身が空でなければよい。**中身の良し悪しは機械には分からない**ので判定しない。
#       機械が見るのは「人が一度立ち止まって書いた」ことだけで、**書いた内容の妥当性は
#       レビューが見る**（#569 の「機械が判断できないことを機械に判断させない」）。
#     · 全角括弧 `（）` と半角括弧 `()` の両方を受ける。**日本語入力の変換次第でどちらも出る**ので、
#       ここで落とすのは綴りの揚げ足取りにしかならない。
set -euo pipefail

usage() {
  echo "usage: $0 <body-file>   (use - for stdin)" >&2
  exit 2
}

[[ $# -eq 1 ]] || usage
BODY_FILE=$1

HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
BOARD_AUDIT="$HERE/../po/board-audit.sh"

# ── 規則を board-audit.sh から取り出す ─────────────────────────────────────────────────
# `CLOSING_RE='...'` の行から、シングルクォートの中身をそのまま取る。
# **取れなければ exit 3。** 規則が読めない状態で「Closes が書いてある」と答えたら、
# それは検査ではなく当てずっぽうになる（#757 の「母数 0 を『きれい』と報告しない」と同じ形）。
if [[ ! -r "$BOARD_AUDIT" ]]; then
  echo "pr-closes: scripts/po/board-audit.sh が読めません（規則の出どころ）。" >&2
  echo "  この検査は board-audit.sh の CLOSING_RE をそのまま使います。写しは持ちません。" >&2
  exit 3
fi
CLOSING_RE=$(sed -n "s/^CLOSING_RE='\(.*\)'[[:space:]]*$/\1/p" "$BOARD_AUDIT" | head -1)
if [[ -z "$CLOSING_RE" ]]; then
  echo "pr-closes: board-audit.sh から CLOSING_RE を取り出せませんでした。" >&2
  echo "  board-audit.sh の書き方が変わったなら、この検査の取り出し方も直してください。" >&2
  echo "  **自前の正規表現に退避しません**（写しが 2 つできた時点で、規則がずれます）。" >&2
  exit 3
fi

# ── 逃げ道の綴り ───────────────────────────────────────────────────────────────────────
# `Closes なし` + 括弧（全角/半角）+ **空でない**中身。
# `[^）)]` に改行は入らない（grep は行単位）ので、閉じ括弧までが 1 行に収まっている必要がある。
NO_ISSUE_RE='Closes[[:space:]]*なし[[:space:]]*[（(][^）)]*[^[:space:]）)][^）)]*[）)]'

if [[ "$BODY_FILE" == "-" ]]; then
  BODY=$(cat)
elif [[ -r "$BODY_FILE" ]]; then
  BODY=$(cat "$BODY_FILE")
else
  echo "pr-closes: 本文を読めません: $BODY_FILE" >&2
  exit 2
fi

# **grep は不一致で 1 を返す**ので `|| true` で受ける（`set -e` の下で黙って落ちるのを防ぐ）。
# `-i` は board-audit.sh の closing_refs() と同じ（あちらも `grep -oEi`）。
CLOSING_HITS=$(printf '%s\n' "$BODY" | grep -oEi "$CLOSING_RE" || true)
NO_ISSUE_HITS=$(printf '%s\n' "$BODY" | grep -oE "$NO_ISSUE_RE" || true)

if [[ -n "$CLOSING_HITS" ]]; then
  # 番号まで出す。**「何かに当たった」ではなく「どの Issue に当たった」を見せる**ので、
  # 取り違え（別の番号を書いた）が出力から読める。
  nums=$(printf '%s\n' "$CLOSING_HITS" | grep -oE '[0-9]+$' | sort -un | sed 's/^/#/' | tr '\n' ' ')
  echo "pr-closes: ok — 閉じる語があります: ${nums% }"
  exit 0
fi

if [[ -n "$NO_ISSUE_HITS" ]]; then
  echo "pr-closes: ok — 対応する Issue が無いことが明示されています: $(printf '%s\n' "$NO_ISSUE_HITS" | head -1)"
  exit 0
fi

cat >&2 <<MSG
pr-closes: この PR の本文に、対応する Issue がどれかが書かれていません。

  次のどちらかを本文に 1 行足してください:

    Closes #N                       ← 対応する Issue がある場合（Fixes / Resolves でも可）
    Closes なし（理由）              ← 対応する Issue が無い場合。**理由は省略できません**

  なぜ止めているか（実測 2026-09-13）:
    **マージ済み PR 300 件のうち閉じる語があるのは 151 件**（直近 50 件では 有 28 / 無 22）。
    **書かれていない PR は、マージしても Issue が open のまま残る。**
    実際に #763 / #771 が取り残され、#783 で作った scripts/po/board-audit.sh は
    **本丸 3 件のうち 1 件しか検出できなかった**（残る 2 件は閉じる語が無かったため）。

  **本文に \`#N\` と数字が出るだけでは通りません。** GitHub が自動クローズに使う語
  （Closes / Fixes / Resolves）が要ります。**語を緩めると無関係な Issue を閉じます**
  （#569。#763 の検索には無関係な PR #450/#698/#461 が引っかかった）。

  **対応する Issue が本当に無い PR は実在します**（作業合意やスプリント文書の更新など）。
  そのときは \`Closes なし（作業合意の更新）\` のように**理由まで**書いてください。
MSG
exit 1
