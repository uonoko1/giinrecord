/**
 * **記号の数と公表値（賛成者数・反対者数）が食い違った行を全部返す**（#826 で佐賀に作り、#844 で 5 県に広げた）。
 *
 * ## なぜ「行ごとに `assert.equal`」をやめたか
 *
 * **この検算は 5 県（宮城・鳥取・島根・佐賀・高知）にあり、5 つとも全行に無条件だった。**
 * **山梨には、公表された賛成者数に議長の `〇` が入っていない行が 2 つある**（再議→否決。#782／#811）。
 * **佐賀にも同じ事象（知事の再議・三分の二未満で否決）の行が実在するが、佐賀では議長を数えているので合っている**（#825）。
 * **つまり「規則」ではなく「県ごとの慣行」で、同じ事象でも数え方が違う。**
 *
 * **だから、いつか落ちる。** **落ちたときに読めるものが「36 !== 35」だけでは、**
 * **`1 行だけ数え方が違う` のか `表の復元が壊れて 26 行ずれた` のかが区別できない**
 * （**#826 の実測: 佐賀 72 行のうち 3 行を食い違わせても、落ちたメッセージに出たのは最初の 1 行だけだった**）。
 * **前者は記録が正しく、後者は記録が偽である。** **どちらも「テストが赤い」では同じに見える。**
 *
 * **検算は緩めない**——**食い違いが 1 行でもあれば、これを使うテストは落ちる。**
 * **変わったのは「落ちたときに全部見える」ことだけである。**
 *
 * ## **賛成・反対の字は県ごとに違う**（呼ぶ側が渡す）
 *
 * | 県 | 賛成 | 反対 |
 * |---|---|---|
 * | 宮城・鳥取・佐賀・高知 | `○` | `×`（U+00D7） |
 * | **島根** | `○` | **`●`** |
 *
 * **#826 の担当者は島根を `○`/`×` で数えて 17 件の偽の不一致を出し、`●` だと気づいて数え直している。**
 * **だから字は既定値にせず、呼ぶ側が県ごとに渡す**（既定値があると、渡し忘れが「合っている」に見える）。
 *
 * **本番側（`data/`）の扱いは別にある**: **`meta.countMismatches`**（#826）が
 * **`buildLocalAssembly` の中で 11 県すべての食い違いを件数として残す**ので、
 * **月次 ETL は止まらず、記録は出たうえで人が見に行ける。**
 * **あちらは `mapped`（各県が凡例から引いた意味）で数える**ので県ごとの字に依存しない。
 * **こちら（パーサのフィクスチャ）は `mapped` になる前の生の字を見る**ので、字を渡す必要がある。
 *
 * ## **本番側では代えられない**（#844 で実測）
 *
 * | 県 | フィクスチャの行 | `data/` で本番側が見ている行 |
 * |---|---:|---|
 * | 宮城 | 160（第398回 50・第399回 110） | **133**（第399回・第400回。**第398回は `data/` に無い**） |
 * | 鳥取 | 133 | 117（1 行は凡例が引けず母数の外） |
 * | 島根 | 112 | 112 |
 * | **高知** | **47** | **0**（**104 行すべて `counts` を出力に入れていないので母数の外**。#757） |
 *
 * ## **`checked`（実際に突き合わせた行の数）も返す**（#757／#844 の変異 3）
 *
 * **食い違いの配列だけを返していたとき、「全行を黙って外す」変異を当てても 4 県とも緑のままだった**
 * （**当たったことは md5 で確認済み。等価変異ではない**）。**「食い違い 0 件」は「見た上での 0」でなければ意味が無い。**
 * **だから呼ぶ側は `checked` も固定する**——**突き合わせる相手が 1 行も無くなったら落ちる。**
 */
export function countMismatchRows<Row extends { counts?: { yes: number | string; no: number | string } }>(
  rows: readonly Row[],
  opts: {
    /** その県で「賛成」を表す字（島根以外は `○`）。 */
    readonly yes: string;
    /** その県で「反対」を表す字（**島根は `●`**）。 */
    readonly no: string;
    /** 行のセル（議員 1 人につき 1 つ）。 */
    readonly cells: (row: Row) => readonly string[];
    /** 落ちたときに人が読む行の名前（議案番号など）。 */
    readonly label: (row: Row) => string;
  },
): { mismatches: string[]; checked: number } {
  const mismatches: string[] = [];
  let checked = 0;
  for (const r of rows) {
    // **`counts` の欄が無い行は突き合わせる相手が公表されていない**ので、外す（#757）。
    // **「合っている」とも「食い違っている」とも言えない。**
    if (!r.counts) continue;
    checked++;
    const cells = opts.cells(r);
    const yes = cells.filter((c) => c === opts.yes).length;
    const no = cells.filter((c) => c === opts.no).length;
    if (yes === Number(r.counts.yes) && no === Number(r.counts.no)) continue;
    mismatches.push(`${opts.label(r)}: 数えた ${opts.yes}${yes} ${opts.no}${no} / 公表 賛成${r.counts.yes} 反対${r.counts.no}`);
  }
  return { mismatches, checked };
}
