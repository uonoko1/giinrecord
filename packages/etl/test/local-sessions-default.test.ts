import { test } from "node:test";
import assert from "node:assert/strict";
import { LOCAL_SOURCES, defaultSessionsFor, DEFAULT_LOCAL_SESSIONS } from "../src/local-assemblies.ts";

/**
 * # 議会ごとの `--sessions` の既定（Issue #901）
 *
 * ## 何が問題だったか
 *
 * **`local-cli.ts` の既定は全議会一律の `--sessions 2` で、月次ワークフローは `--sessions` を渡さない。**
 * **その結果、本番に出ているのは一次資料のごく一部だった**（三重は index の賛否 PDF 151 本のうち
 * **読めるのが 84 本、出ているのは 13 本ぶん（365 件）だけ**）。
 *
 * **「広げてよいか」ではなく「広げたとき何が起きるかを測ったか」が問われている**（#901）。
 *
 * ## **なぜ議会ごとに違う値なのか**——**一律に広げてはいけない**
 *
 * **地方の名簿は「今の名簿」1 枚しか公表されていない**（`LocalMemberTerm` は `asOf` しか持たない）。
 * **一般選挙をまたいだ採決にその名簿を当てると、引退した議員の票が今の別人に付きうる**
 * ——**利用者から検出できない虚偽である**（#569 の重いほう。#928 の検査も捕まえない）。
 *
 * **だから既定は「その議会で、今の任期に収まる会期の数」でなければならない。**
 * **任期の境は議会ごとに違うので、1 つの数では書けない。**
 *
 * ## **三重を 4 にした根拠**（2026-09-20、index の賛否 PDF 151 本すべてを取得して実測）
 *
 * **会期ごとに「PDF に出る氏名の集合」を数えると、一般選挙の年に 9 人が入れ替わる**
 * （`.measure/901/term-boundary.ts`。**選挙の日付を外から持ち込まず、一次資料だけで境を見た**）:
 *
 * | 会期 | 氏名 | 直前と共通 | **入れ替わり** | 採決の期間 |
 * |---|---:|---:|---:|---|
 * | r06 | 49 | 46 | 3 | 2024-02-20〜2024-11-21 |
 * | **r05-2** | 48 | 48 | **0** | **2023-05-12〜2023-12-21** |
 * | **r05-1** | 49 | 40 | **9** | **2023-03-02〜2023-03-17** |
 *
 * **同じ形の 9 人の入れ替わりが h31（2019-03）と h27-1（2015-03）にもある**——**4 年ごと。**
 * **r05-2 から r08 までは入れ替わりが 0〜3 人で、これは任期中の辞職・補選の規模である。**
 *
 * **だから `--sessions 4`（r08 / r07 / r06 / r05-2）が、今の任期に収まる最大である。**
 * **`--sessions 5` は r05-1 を足し、一般選挙をまたぐ。**
 *
 * ## **広げて何が増えたか**（母数つき。#757）
 *
 * | | `--sessions 2` | **`--sessions 4`** |
 * |---|---:|---:|
 * | 採決 | 365 | **733** |
 * | セル | 17,032 | **34,590** |
 * | 不明セル（推定せず残した） | 0 | **43** |
 * | **寄らなかった氏名**（安全側） | 3 | **6** |
 * | **寄らなかった票** | 417 | **2,151** |
 * | `rosterAsOf` からの最大の隔たり | 302 日 | **921 日**（上限 1,461） |
 *
 * **名簿の 47 人は、4 会期すべてに 1 人残らず現れる**（この範囲に「名簿にいるのに票が無い」人はいない）。
 * **寄らなかった 6 人はいずれも辞職・引退した議員で、票は `memberId` 空のまま残る**（#529）。
 *
 * ## **徳島を 4 にした根拠**（2026-09-20、到達できる 28 会期・28 本の PDF をすべて取得して実測）
 *
 * **徳島で効いている上限は名簿ではなく「読めるか」である**——**任期の境よりずっと手前で読めなくなる。**
 *
 * | `--sessions` | 追加の会期 | PDF | 読めた | 採決 | 止まる理由 |
 * |---:|---|---:|---:|---:|---|
 * | 2 | 2026-09 / 2026-06 | 2 | 2 | **21** | — |
 * | 3 | ＋2026-02 | 5 | 5 | **106** | — |
 * | **4** | **＋2025-11** | **7** | **7** | **153** | — |
 * | 5 | ＋2025-09 | — | — | — | **会期ページが例外**（リンク文言が半角括弧で `PDF_TEXT` に合わない。#875） |
 * | 6〜18 | 2025-06 〜 2022-05 | 21 | **0** | **0** | **1 本も読めない**（#875 の A 群・② 群） |
 *
 * **一般選挙の境は 2023-02 と 2023-05 のあいだ**（**氏名の集合が IN 13 / OUT 11 で不連続になる。
 * 9 会期 2023-05〜2025-11 は 38 人でまったく動かない**）——**`--sessions 4` はその内側にある。**
 *
 * | | `--sessions 2` | **`--sessions 4`** |
 * |---|---:|---:|
 * | PDF | 2 | **7** |
 * | 採決 | 21 | **153** |
 *
 * **`--sessions 2` は今や 2026-02 の 85 件を落とす**——**2026-09 会期が増えて窓から押し出されたため。**
 * **本番に出ている 105 件は 2026-06 ＋ 2026-02 で、今の既定ではもう再現しない。**
 *
 * ## **高知を 5 にした根拠**（2026-09-20、index の賛否 PDF 65 本すべてを取得して実測）
 *
 * **高知で効いている上限は名簿でも「読めるか」でもなく、`glyphs.ts` の 1 つの安全弁である。**
 *
 * | `--sessions` | 足す会期 | 採決（累計） | セル（累計） | **寄らなかった氏名 / 票** | 止まる理由 |
 * |---:|---|---:|---:|---|---|
 * | 2 | 2026-06 / 2026-02 | **104** | 3,744 | 0 / 0 | （本番の値） |
 * | 3 | ＋2025-12 | **179** | 6,369 | 2 / 150 | **直す前はここで止まっていた**（請願の枝番 `請第1-1号`） |
 * | 4 | ＋2025-09 | **197** | 7,017 | 3 / 204 | — |
 * | **5** | **＋2025-06** | **221** | **7,881** | **3 / 276**（3.50%） | — |
 * | 6 | ＋2025-02 | — | — | — | **`rotated/scaled text matrix [1,0,0,1.0000200271606445]`** |
 *
 * **2025-02 は `/Rotate 0` で、text matrix の `a` か `d` だけが `1.0000200271606445`**
 * （実測: `[1.00002,0,0,1]` ×3,664、`[1,0,0,1.00002]` ×1,096）。
 * **`glyphs.ts` の `showText` は `a` / `d` を字送りに掛けていない**ので、
 * **通せば 0.002% ずれた位置で文字を読むことになる。正しい足し方を実データで検証していないので通さない。**
 *
 * **一般選挙の境はずっと先にある**——**会期ごとに PDF に出る氏名の集合を 31 本ぶん数えると、
 * 2023-02 と 2023-05臨時 のあいだに IN 10 / OUT 9 の不連続が 1 回だけ出る**
 * （**その次は 2019-05臨時 の IN 8 / OUT 8**）。**`--sessions 14` までが任期の内側で、5 はその手前である。**
 * **つまり高知では「名簿が古すぎる」より先に「読めない 1 本」が来る。**
 *
 * ## **秋田を 29 にした根拠**（2026-09-20、index の賛否 PDF 154 本すべてを取得して実測）
 *
 * ### **秋田だけ数の単位が違う**——**「29 本会議日」であって「29 定例会」ではない**
 * **賛否 PDF が 1 本会議日に 1 本**なので（`akita/index.ts`）、**`--sessions N` は N 本の PDF を指す。**
 * **1 つの定例会に PDF が 7 本ある年もある。** **三重・徳島の 4 と秋田の 29 は同じ桁の話ではない。**
 *
 * ### **秋田は読める本が尽きない**——**154 / 154 本すべてが読める**（実測。失敗 0）
 * **だから止める位置を決めるのは「読めるか」ではなく「名簿が当たるか」だけである。**
 *
 * ### **境は 29 本目と 30 本目のあいだ**（**選挙の日付を外から持ち込まず、氏名の集合だけで見た**）
 *
 * | 本 | 議決日 | 氏名 | 1 つ古い本と共通 | **IN** | **OUT** |
 * |---:|---|---:|---:|---:|---:|
 * | 27〜28 | 2023-07-28 / 2023-07-06 | 41 | 41 | 0 | 0 |
 * | **29** | **2023-05-16** | **41** | **34** | **7** | **9** |
 * | 30〜36 | 2023-03-10〜2022-09-20 | **43** | 43 | **0** | **0** |
 *
 * **5 人以上の入れ替わりが出る境は 154 本でここ 1 か所だけ**（議員数も 41 ↔ 43 で変わる）。
 *
 * ### **`#928` の検査は、この境を 1 度も捕まえない**（**余地があることは安全ではない**）
 * **`rosterAsOf` 2026-07-24 から 2023-05-16 まで 1,165 日、選挙の前の 2023-03-10 でも 1,232 日。**
 * **どちらも上限 1,461 日の内側である。** **止める位置を決めたのは氏名の集合の不連続のほうである。**
 *
 * | | `--sessions 5`（本番に出ていた値） | **`--sessions 29`** |
 * |---|---:|---:|
 * | 採決 | 157 | **785** |
 * | セル | 6,437 | **32,022** |
 * | **不明セル** | **0** | **0**（**154 / 154 本が読めるので増えない**） |
 * | **寄らなかった氏名**（安全側） | 0 | **2**（沼谷 純・鈴木 健太。どちらも任期中に退いた） |
 */

test("#901 既定は議会ごとに持つ（全議会一律の 1 つの数にしない）", () => {
  // **母数**: 11 議会すべてに既定がある（新しい議会を足して書き忘れたら落ちる）
  const names = Object.keys(LOCAL_SOURCES).sort();
  assert.equal(names.length, 11, `議会 ${names.length}`);
  for (const n of names) {
    const v = defaultSessionsFor(n);
    assert.ok(Number.isInteger(v) && v >= 1, `${n}: 既定 ${v} が 1 以上の整数でない`);
  }
});

test("#901 三重・徳島・奈良は 4、高知は 5、秋田は 29、他の 6 議会は 2 のまま（測った議会だけ広げる）", () => {
  assert.equal(defaultSessionsFor("mie"), 4, "三重は令和5年第2回定例会まで（2023年4月の一般選挙の後）");
  assert.equal(defaultSessionsFor("tokushima"), 4, "徳島は令和7年11月定例会まで（5 会期目は会期ページが例外、6 会期目以降は 1 本も読めない）");
  assert.equal(defaultSessionsFor("kochi"), 5, "高知は令和7年6月定例会まで（6 会期目の 2025-02 は text matrix が 1.00002 倍で止まる）");
  // **秋田の単位は「本会議日」**（他の 10 議会は「定例会」）。**29 は 29 本の PDF ＝ 2023-05-16 以降**
  assert.equal(defaultSessionsFor("akita"), 29, "秋田は 2023-05-16 の本会議日まで（2023年4月の一般選挙の後。30 本目が選挙の前）");
  // **秋田だけ桁が違うのは単位が違うから**——**他県の 4・5 と比べて「大きすぎる」のではない**
  assert.ok(defaultSessionsFor("akita") > defaultSessionsFor("kochi") * 5, "**単位が違うので桁も違う**（本会議日 vs 定例会）");
  // **奈良は令和7年9月定例会まで**（5 会期目の 令和7年6月 はセルの `-` U+002D が凡例の `―` U+2015 に無い。
  // **共有の字形表で寄せると滋賀の凡例から `-`（欠席）が引けなくなる**ので寄せない。
  // 測定は `nara-sessions-window.test.ts`）
  assert.equal(defaultSessionsFor("nara"), 4, "奈良は令和7年9月定例会まで（5 会期目は `-` U+002D が凡例に無い）");
  const measured = ["mie", "tokushima", "kochi", "akita", "nara"];
  const others = Object.keys(LOCAL_SOURCES).filter((n) => !measured.includes(n));
  assert.equal(others.length, 6, `測っていない議会 ${others.length}`);
  assert.deepEqual(
    others.filter((n) => defaultSessionsFor(n) !== DEFAULT_LOCAL_SESSIONS),
    [],
    "**測っていない議会を巻き込んで広げない**（#901 は 1 県ずつ）",
  );
  assert.equal(DEFAULT_LOCAL_SESSIONS, 2, "これまでの一律の既定");
});

test("#901 知らない議会の名前には既定の 2 を返す（CLI が落ちる前にここで壊れない）", () => {
  assert.equal(defaultSessionsFor("no-such-assembly"), DEFAULT_LOCAL_SESSIONS);
  assert.equal(defaultSessionsFor(""), DEFAULT_LOCAL_SESSIONS);
});
