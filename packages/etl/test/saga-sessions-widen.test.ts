/**
 * # 佐賀の `--sessions` の既定を 2 → 13 にした根拠（Issue #901 / #961）
 *
 * ## **まず「23 しか無い」のか「23 しか読めていない」のかを切り分けた**（#757）
 *
 * **本番の `data/assemblies/pref-41/meta.json` は 23 採決・2 会期だった。**
 * **23 は先行 9 県の中で最も少ないので、一次資料そのものが少ない可能性をまず疑った。**
 * **答えは「一次資料は在る。実装が 2 本しか見に行っていなかった」である。**
 *
 * **母数**（2026-09-21、`runSaga` を実際に走らせて数えた。**数えていないものを推定していない**）:
 *
 * | | 本数 |
 * |---|---:|
 * | **今の任期（令和5年4月30日〜令和9年4月29日）に索引が持つ会期** | **20** |
 * | **読めた** | **13** |
 * | 読めなかった: **賛否 PDF のリンクがそもそも無い**（令和8年11月定・8年9月定。会期中） | 2 |
 * | 読めなかった: **PDF に文字層が無い**（令和7年11月定・7年6月定・6年11月定・6年9月定・6年6月定） | 5 |
 *
 * **13 + 2 + 5 = 20。** **対象が 0 本なら error、という約束どおり、
 * 「落ちた 7 本」は `unreadableSources`（5 本）とログ（2 本）の両方に理由つきで残る。**
 *
 * ## **欠陥: `--sessions N` が「読める会期 N 本」を返していなかった**（この PR が直した）
 *
 * **`index.ts` の内側のループは「読めた会期が N 本そろったら止める」と書いてあるが、
 * 外側の索引の歩きは `targets.length >= opts.sessions` で止まっていた**——
 * **`targets` は「索引の候補」であって「読めた会期」ではない。**
 * **佐賀は読めない会期が 20 本中 7 本もあるので、候補の本数で止めると足りないまま返る。**
 *
 * **直す前に実測した（2026-09-21、本番の一次資料）:**
 *
 * | 頼んだ N | **返った会期** | 採決 | 最古の採決 |
 * |---:|---:|---:|---|
 * | 2 | 2 | 23 | 2026-04-21 |
 * | 4 | **3** | 101 | 2026-03-06 |
 * | 8 | **6** | 201 | 2025-03-07 |
 * | 13 | **8** | 277 | 2024-03-14 |
 * | 20 | **14** | 445 | **2023-03-10**（**一般選挙の前に届いてしまう**） |
 *
 * **直した後は 13 を頼めば 13 本、14 を頼めば 14 本返る**（下のログの実測）。
 * **この欠陥があるうちは「既定をいくつにするか」を決められない**——
 * **N を増やしたとき何会期増えるかが読めず、`20` のような素朴な値を置くと
 * 一般選挙の境を黙って踏み越えるからである**（#569 の重いほう）。
 *
 * ## **止める位置は「読めるか」ではなく「名簿が当たるか」で決めた**
 *
 * **会期ごとに `runSaga` の出力（`rollCalls[].votes[].nameText`）から氏名の集合を作り、
 * 隣り合う会期で数えた**（**選挙の日付を外から持ち込まず、一次資料の氏名だけで境を見る**）:
 *
 * | # | 会期 | 採決 | 累計 | 氏名 | IN | OUT |
 * |---:|---|---:|---:|---:|---:|---:|
 * | 1 | 令和8年6月定例会 | 21 | 21 | 37 | 0 | 0 |
 * | 2 | 令和8年4月臨時会 | 2 | 23 | 37 | 2 | 2 |
 * | 3 | 令和8年2月定例会 | 78 | 101 | 37 | 2 | 2 |
 * | 4 | 令和7年9月定例会 | 27 | 128 | 37 | 0 | 0 |
 * | 5 | 令和7年4月臨時会 | 1 | 129 | 37 | 2 | 2 |
 * | 6 | 令和7年2月定例会 | 72 | 201 | 37 | 1 | 1 |
 * | 7 | 令和6年4月臨時会 | 2 | 203 | 37 | 0 | 0 |
 * | 8 | 令和6年2月定例会 | 74 | 277 | 37 | 0 | 0 |
 * | 9 | 令和5年11月定例会 | 31 | 308 | 37 | 0 | 0 |
 * | 10 | 令和5年9月定例会 | 24 | 332 | 37 | 0 | 0 |
 * | 11 | 令和5年6月定例会 | 30 | 362 | 37 | 0 | 0 |
 * | 12 | 令和5年5月臨時会（5月29日） | 2 | 364 | 37 | 0 | 0 |
 * | **13** | **令和5年5月臨時会（5月9日から11日まで）** | 2 | **366** | 37 | 0 | 0 |
 * | **14** | **令和5年2月定例会** | 79 | 445 | **36** | **4** | **5** |
 *
 * **2・3・5・6 の IN/OUT 2・2・2・1 は名簿の動きではない**——
 * **一次資料どうしが 2 人ぶん食い違っているだけである**（`rollcalls.ts` の docblock。
 * `猪村利恵子`↔`猪村理恵子`、`桃崎祐介`↔`桃崎裕介`）。**行ったり来たりしているので、
 * 「入れ替わった」のではなく「同じ人を 2 通りに書いている」ことが集合の動きから分かる。**
 *
 * **13↔14 だけが本物の不連続である**（下のテストが一次資料から確かめる）。
 *
 * ## **#928 の `rosterAsOf` の窓は、この境を捕まえない**（#961。**佐賀は先行 9 県でいちばん外れている**）
 *
 * | | 最古の採決 | `rosterAsOf`（2025-04-01）からの日数 | 上限 1,461 日 |
 * |---|---|---:|---|
 * | `--sessions 13` | 2023-05-11 | 691 | 内側 |
 * | **`--sessions 14`（境の向こう側）** | **2023-03-10** | **753** | **内側（708 日も余っている）** |
 *
 * **青森（#959）は「境の 4 会期後ろで初めて鳴る」だったが、佐賀は上限の半分そこそこで境を越える。**
 * **窓に頼れば、引退した 4 人の票が今の名簿に当たりうる状態のまま黙って通る。**
 * **日数は名簿が変わった「かもしれない」ことしか言えず、変わった「こと」を言えない**（#961）。
 */
const fx = (name: string): Buffer => readFileSync(new URL(`./fixtures/saga/${name}`, import.meta.url));

/** 13 本目（**今の任期の中でいちばん古い会期**）＝ 令和5年5月臨時会（5月9日から11日まで） */
const IN_TERM = "3_96145_279859_up_jsqwevkw.pdf";
/** 14 本目（**一般選挙の向こう側**）＝ 令和5年2月定例会 */
const ACROSS = "3_95237_272348_up_pqtj45d7.pdf";

/**
 * ## **境は 13↔14 にある**——**一次資料の氏名の集合だけで見る**
 *
 * **2 本の PDF に出る氏名を突き合わせる。** **選挙の日付も、任期の日数も使っていない。**
 * **`parseVotePdf` の出力（`members[].nameText`）をそのまま数える**——
 * **自分で PDF を組み直して突き合わせない**（#757 / 青森 #959 の変異の分類 4）。
 */
test("#901 佐賀の境は 13↔14 会期: 令和5年2月定例会 で IN 4 / OUT 5 の不連続が出る（一般選挙 2023-04）", async () => {
  const inTerm = await parseVotePdf(fx(IN_TERM));
  const across = await parseVotePdf(fx(ACROSS));
  // **母数**（0 人なら「一致した」ではなく「数えていない」。#757）
  assert.equal(inTerm.members.length, 37, "13 本目の氏名（母数）");
  assert.equal(across.members.length, 36, "14 本目の氏名（母数。**人数からして違う**）");

  const a = new Set(inTerm.members.map((m) => m.nameText));
  const b = new Set(across.members.map((m) => m.nameText));
  const IN = [...b].filter((n) => !a.has(n));
  const OUT = [...a].filter((n) => !b.has(n));
  assert.deepEqual(IN.sort(), ["中倉政義", "井上祐輔", "川﨑常博", "稲富正敏"].sort(),
    "**14 本目にだけ出る 4 人**（この PR が 13 で止める理由）");
  assert.deepEqual(OUT.sort(), ["指山清範", "猪村利恵子", "石丸太郎", "酒井幸盛", "青木一功"].sort(),
    "**13 本目にだけ出る 5 人**");
});

/**
 * ## **「入ってくる 4 人が今の名簿に 1 人もいない」ことが、境である証拠**
 *
 * **IN / OUT の人数だけでは「表の書き方が変わった」と区別できない。**
 * **決め手は「その 4 人を今の名簿に当てられるか」である**——
 * **`matchName`（本番の名寄せそのもの）に通して、1 人も当たらないことを見る。**
 *
 * **裏返しの対照も置く**: **OUT の 5 人は全員、今の名簿に当たる**（現職である）。
 * **これが無いと「名寄せがそもそも動いていない」のか「本当に居ない」のかが区別できない。**
 */
test("#901 14 本目に入ってくる 4 人は今の名簿に 1 人もいない（出ていく 5 人は全員いる）", () => {
  const roster = parseRoster(fx("roster.html").toString("utf-8"));
  assert.equal(roster.members.length, 37, "名簿の母数");
  assert.equal(roster.asOf, "2025-04-01");
  assert.equal(roster.termText, "（任期）令和5年4月30日～令和9年4月29日",
    "**任期の原文**（**14 本目の 令和5年2月定例会 はこの任期の前**）");

  const IN = ["中倉政義", "川﨑常博", "井上祐輔", "稲富正敏"];
  const OUT = ["指山清範", "青木一功", "石丸太郎", "酒井幸盛", "猪村利恵子"];
  assert.deepEqual(IN.filter((n) => matchName(n, roster.members).memberId !== ""), [],
    "**14 本目にだけ出る 4 人は、今の名簿に 1 人も当たらない**（＝一般選挙で退いた）");
  assert.deepEqual(OUT.filter((n) => matchName(n, roster.members).memberId === ""), [],
    "**13 本目にだけ出る 5 人は、今の名簿に全員当たる**（否定的対照。名寄せは動いている）");
});

/**
 * ## **#928 の窓では止まらない**（#961。**この PR がいちばん外れた例を足す**）
 *
 * **14 本目まで広げても `rosterAsOf` から 753 日**で、**上限 1,461 日の内側に 708 日も余る。**
 * **青森は「境の 4 会期後ろで鳴った」、秋田は「1 度も鳴らなかった」、
 * 佐賀は「上限の半分そこそこで境を越える」**——**3 県とも同じ結論を指している。**
 *
 * **この計算に使う日付は、どちらも一次資料から来ている**
 * （`rosterAsOf` は名簿ページの「令和7年4月1日現在」、`2023-03-10` は 14 本目の PDF の最古の議決日）。
 */
test("#901 #928 の 1,461 日の窓は佐賀の境を捕まえない（境の向こう側でも 753 日、余り 708 日）", () => {
  const days = (from: string, to: string) =>
    Math.round((Date.parse(`${to}T00:00:00Z`) - Date.parse(`${from}T00:00:00Z`)) / 86_400_000);
  // **実装の定数をそのまま使う**（ここに 1,461 と書き写すと、
  // **`LOCAL_TERM_DAYS` を変えてもこのテストが気づかない**）
  const LIMIT = LOCAL_TERM_DAYS;
  assert.equal(LIMIT, 1_461, "地方自治法 93 条 1 項の 4 年（うるう年 1 回を含む）");
  const rosterAsOf = "2025-04-01";
  // **13 本目まで**（この PR の既定）
  assert.equal(days("2023-05-11", rosterAsOf), 691, "`--sessions 13` の最古の採決までの日数");
  // **14 本目**（境の向こう側。**それでも窓の内側**）
  assert.equal(days("2023-03-10", rosterAsOf), 753, "`--sessions 14` の最古の採決までの日数");
  assert.ok(days("2023-03-10", rosterAsOf) < LIMIT, "**境を越えても窓の内側**（#928 は鳴らない）");
  assert.equal(LIMIT - days("2023-03-10", rosterAsOf), 708, "**余り 708 日**（上限の半分近くが余ったまま境を越える）");
});

/** **既定が 13 であること**（上の 3 つの測定の結論。ここだけ動かしても測定は動かないので、両方置く） */
test("#901 佐賀の既定は 13（令和5年5月臨時会まで。14 本目は一般選挙の前）", () => {
  assert.equal(defaultSessionsFor("saga"), 13);
});
