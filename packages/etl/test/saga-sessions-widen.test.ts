  const roster = parseRoster(fx("roster.html").toString("utf-8"));
  assert.equal(roster.members.length, 37, "名簿の母数");
  assert.equal(roster.asOf, "2025-04-01");
  assert.equal(roster.termText, "（任期）令和5年4月30日～令和9年4月29日",
    "**任期の原文**（**14 本目の 令和5年2月定例会 はこの任期の前**）");

  const IN = ["中倉政義", "川﨑常博", "井上祐輔", "稲富正敏"];
  const OUT = ["指山清範", "青木一功", "石丸太郎", "酒井幸盛", "猪村利恵子"];
