/**
 * 議案の件名（LocalRollCall.title）だけに掛ける字の正規化（#648）。
 *
 * 島根の表決 PDF の文字層は「長」を康熙部首の ⾧（U+2FA7）で持っており、本番の議案名が
 * 「議⾧辞職の件（日程追加）」と出ていた。島根県議会の公式サイト（HTML）は普通の 長（U+9577）で
 * 書いている（2026-09-08 実測: U+2FA7 が 0 件 / U+9577 が 10 件）ので、⾧ は議会の表記ではなく
 * PDF の文字層だけの都合。件名は「議会がその議案をどう呼んだか」なので、ここは公式サイトに合わせる。
 *
 * **件名にしか掛けない。** 氏名（nameText / name）と凡例の原文（LocalVote.raw）には掛けない:
 *   - `vote.raw` は「PDF にこう書いてあった」という事実の保存（`{"legend":"議長","mapped":"投票なし","raw":"議⾧"}`）。
 *     Web の判と凡例はこの原文を見せて意味を括弧で併記する設計なので、畳むと事実が消える。
 *   - 氏名は本人の表記そのもの。data/ には 岡﨑 哲也（高知）の 﨑（U+FA11）が 106 回あり、
 *     これは文字コードの事故ではなく本人の名前。突き合わせのときだけ畳むのは name-match.ts の仕事で、
 *     data/ に書く氏名は原文のまま（#643）。
 *
 * **NFKC は掛けない。** NFKC は全角英数字（Ａ→A）や合字（㈱→(株)）も変えるので、件名の原文が広く変わる。
 * ここは表に載せた字だけを置き換える。
 */

/**
 * 件名で畳む字。康熙部首（U+2F00–U+2FDF）のうち、実データに出ていて、かつ
 * 公式サイトが対応する統合漢字で書いているものだけを入れる。
 * 「見つかった字を全部畳む」表にはしない（U+FA11 﨑 のように、畳んではいけない字があるため）。
 */
const TITLE_CHARS: Readonly<Record<string, string>> = {
  "⾧": "長", // ⾧ 康熙部首「長」→ 長（U+9577）。島根の表決 PDF、data/ に 409 回（うち件名 185 回）
};

const TITLE_RE = new RegExp(`[${Object.keys(TITLE_CHARS).join("")}]`, "gu");

/** 件名の字を正規化する（表に無い字は 1 文字も変えない）。 */
export function normalizeTitle(title: string): string {
  return title.replace(TITLE_RE, (ch) => TITLE_CHARS[ch]!);
}
