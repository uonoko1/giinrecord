/**
 * 表決 PDF のセルの記号 → 凡例の記号（字形の揺れを寄せる。Issue #674）。
 *
 * ## 何が問題か
 * **凡例に書かれている記号と、本文セルに実際に出ている記号のコードポイントが違う PDF がある。**
 * #671 が 5 本の PDF を開いて 3 本で実測した:
 *   - 広島 Ｒ07.4  凡例 `○` U+25CB ／ 本文 `〇` U+3007 が 15 個・U+25CB は 0 個 → **賛成セルが 1 つも取れない**
 *   - 兵庫 第374回 同じページ・同じ表の中で `○` U+25CB 265 個と `〇` U+3007 167 個が**混在**
 *   - 熊本県 令和5年2月 凡例 `×` U+00D7 ／ 本文の唯一の反対票が `✕` U+2715
 * **熊本県のケースは「記録が出ない」ではなく「違う記録が出る」側**——
 * 反対票が凡例に無い値として落ちれば、その議案は「全会一致」に見える（#569）。
 *
 * ## ここが寄せるのは字形の揺れだけで、意味の推定ではない
 * `〇`（U+3007 IDEOGRAPHIC NUMBER ZERO）と `○`（U+25CB WHITE CIRCLE）は**同じ字形の別コードポイント**で、
 * 読み手には区別が付かない。`✕`（U+2715 MULTIPLICATION X）と `×`（U+00D7 MULTIPLICATION SIGN）も同じ。
 * **寄せた先の記号が凡例に無ければ、これまでどおり例外になる**（`checkCellsAgainstLegend`）。
 * **「凡例に無い値が出たら例外」という原則（#569「推定しない」）は緩めていない。**
 * `△`→`○` のような**意味の推定はしない**。ここに足してよいのは
 * 「Unicode の別コードポイントだが同じ字形」だけで、根拠は実測（その PDF で凡例と本文が食い違った記録）に限る。
 *
 * ## `raw` は原文のまま
 * **寄せるのは凡例を引くときだけ。** 各県の `rollcalls.ts` が書く `LocalVote.raw` はセルの原文で、
 * `〇` U+3007 は `〇` のまま残る（徳島の本番データ 74 件がその形）。
 *
 * ## `〇` U+3007 は「記号」ではなく漢字（Han script）
 * **「漢字を除いて記号だけ数える」走査では拾われない。** #671 の担当者自身がその罠に落ち、
 * 兵庫の 167 個が最初の集計で見えていない。**この表を実測で育てるときは候補文字を明示列挙して数えること。**
 *
 * ## 氏名の字形の揺れはここではない
 * `髙`/`高`・`﨑`/`崎`・`⾧`/`長`（康熙部首）のような**氏名の字形は `name-match.ts` の `ITAIJI`**（#636）。
 * 突き合わせの相手（名簿）も畳み方も違うので、混ぜない。
 * **滋賀の `辻`→`□`（U+25A1）は字形の揺れではなく字が失われた形**なので、どちらの表にも足さない
 * （寄せる先が無い。`□` を `辻` と読むのは推定＝別人の記録を作る側）。
 */

/**
 * 見た目が同じ別コードポイント → 凡例で使われるほうの記号。
 * 出どころ（この揺れを実際に見た PDF）を必ず添えること。
 */
const GLYPH_VARIANTS: Readonly<Record<string, string>> = {
  "〇": "○", // U+3007 IDEOGRAPHIC NUMBER ZERO → U+25CB WHITE CIRCLE（徳島 1064407.pdf 74 個、広島 Ｒ07.4、兵庫 第374回）
  "✕": "×", // U+2715 MULTIPLICATION X → U+00D7 MULTIPLICATION SIGN（熊本県 令和5年2月。唯一の反対票）
};

/**
 * セルの原文 → 凡例を引くための鍵。表に無ければ原文のまま返す（勝手に増やさない）。
 * セルが 2 文字以上（島根の「棄権」「除斥」「議⾧」）でも、1 文字ずつ寄せる。
 */
export const legendKey = (raw: string): string => [...raw].map((c) => GLYPH_VARIANTS[c] ?? c).join("");

/** 実測したときにこの表が何を覆っているかを示すための一覧（テスト用）。 */
export const glyphVariantPairs = (): [string, string][] => Object.entries(GLYPH_VARIANTS);
