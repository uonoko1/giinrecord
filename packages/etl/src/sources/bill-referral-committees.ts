const ERAS: readonly ReferralEra[] = [ERA_MODERN, ERA_1998];

/**
 * その付託日の表（数えていない時期なら undefined）。
 * ISO の日付は辞書順が時系列順なので、文字列のまま比較してよい。
 */
function eraOf(date: string): ReferralEra | undefined {
  return ERAS.find((e) => e.from <= date && date <= e.to);
}


/**
 * **その付託日について、この許可リストが根拠を持つか。**
 *
 * **偽なら、その付託先は委員会名として出さない。**
 * **「知らない時期だから通す」は allowlist ではない**——知らないものを通さないのが allowlist である。
 */
export function referralAllowlistCoversDate(date: string): boolean {
  return eraOf(date) !== undefined;
}

/** 数えた期間（テストが母数を固定するため。古い順）。 */
export function countedReferralPeriods(): readonly { from: string; to: string; countedFrom: string }[] {
  return [...ERAS].sort((a, b) => (a.from < b.from ? -1 : 1)).map((e) => ({ from: e.from, to: e.to, countedFrom: e.countedFrom }));
}

/**
 * **その付託日・その院**の許可リスト（テストと検査が数えるため。並びは表のまま＝件数の降順）。
 * **数えていない時期では空**（「何も許可していない」＝全部止まる）。
 */
export function referralCommitteeAllowlist(date: string, house: House): readonly string[] {
  const era = eraOf(date);
  if (era === undefined) return [];
  return house === "shugiin" ? era.shugiin : era.sangiin;
}

/** 全期間・全院を合わせた異なり名（テストが母数を固定するため）。 */
export function allReferralCommittees(): readonly string[] {
  return [...new Set(ERAS.flatMap((e) => [...e.shugiin, ...e.sangiin]))];
}

/**
 * **その付託日・その院の一次資料に、この委員会名が記録されていたか。**
 *
 * **偽なら付託先として出してはいけない。** 知らない値は「新しい委員会かもしれない」ではなく
 * **「私たちがまだ数えていない値」**であり、委員会名として出すのは推測になる。
 *
 * **偽になる 4 つの場合**（どれも「止める」に倒す）:
 *   1. **数えていない時期**（1999〜2019年・2026年8月以降）——表に根拠が無い
 *   2. **その時期には無かった名前**（2026 年の付託に `大蔵`）——別の時代の名前
 *   3. **その院の表に無い名前**（衆の欄に `外交防衛`）——院を取り違えている
 *   4. **どの表にも無い名前**——新しい表現か、切り出しを誤っている
 *
 * **知らない院も常に偽**（`House` は今 2 つだが、増えたときに黙って通さないため）。
 */
export function isKnownReferralCommittee(date: string, house: House, committee: string): boolean {
  return referralCommitteeAllowlist(date, house).includes(committee);
}
