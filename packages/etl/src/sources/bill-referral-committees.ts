/**
 * 議案の付託先として **出してよい委員会名の許可リスト**（#1133）。
 *
 * ## denylist をやめた理由（実測）
 *
 * **ここは最初「委員会でない値を除外する」denylist だった**（`審査省略` / `審査省略要求` の 2 語）。
 * **列挙に無い値は委員会名として素通りする。**
 * **実際に素通りした**: 最初の実装は `審査省略` の 1 語しか持っておらず、
 * **`審査省略要求`（衆 2 件。`204-決議-2` 解任決議案 / `201-決議-3` 不信任決議案）を
 * 委員会名として出していた。** 1,941 件を全数で数えるまで誰もそれに気づいていない。
 *
 * **この形はこのサイトの原則に反する。**
 * 「推測を出さない」はずのサイトが、**一次資料に新しい表現が出た瞬間に黙って推測を出す。**
 * **「記録が出ない」と「別人の記録が出る」は同じ重さではない**（`docs/WORKING_AGREEMENT.md`）。
 * 知らない値を委員会名として出すのは後者であり、**利用者からは検出できない。**
 *
 * ## allowlist が「これで全部」と言える範囲
 *
 * **言えるのは「値の集合」についてだけである。**
 * 付託先の欄に入る値は**有限の名前**であって、自由記述ではない（下の「数えた結果」）。
 * **列挙に無い値は、それが何であれ止まる**——denylist と違い、語を書き足さなくても、
 * **次に新しい表現が出た人が捕まる。**
 *
 * **言えないこと**は下の「塞げていない形」に列挙する。
 *
 * ## 数えた結果（2026-09-30。`docs/research/bill-referral.md`）
 *
 * **2 回に分けて全数取得した**（どちらも失敗 0 件・付託欄の欠落 0 件）:
 *   第195〜221回  `data/bills/index.json` の **1,941 件**（4 欄 = 7,764 欄）
 *   第142回        一覧 `kaiji142.htm` の **241 件**（4 欄 = 964 欄）
 *
 * 付託先の位置に現れた値のうち、**委員会・審査会の名前は 64 種類**
 * （**衆 40 / 参 40。うち両院に出るのは 16**）。
 * **委員会でない値は 2 種類だけ**（`審査省略` / `審査省略要求`）。
 *
 * **予備付託の欄は新しい名前を 1 つも増やさない**（実測）。なので院ごとに 1 つの集合でよい。
 *
 * ## 院ごとに分ける理由
 *
 * **同じ議案でも衆と参は別の名前で記録する**（衆 `財務金融` / 参 `財政金融`、
 * 衆 `外務` / 参 `外交防衛`、衆 `文部科学` / 参 `文教科学`）。
 * **64 種類のうち両院に出るのは 16 だけで、衆のみ 24・参のみ 24 である。**
 * **両院を 1 つの集合にすると、`外交防衛` が衆の欄に現れても通ってしまう。**
 * 院ごとに持てば、**その院の一次資料に無い名前**として止まる。
 *
 * ## 中黒（`・`）の有無も揃えない
 *
 * **参議院は 1998 年に `外交・防衛`、2019 年以降は `外交防衛` と記録している**
 * （`財政・金融` / `財政金融`、`文教・科学` / `文教科学`、`経済・産業` / `経済産業` も同じ）。
 * **表記を正規化して 1 つにまとめない**——**どちらも一次資料の原文であり、
 * どちらに寄せても、その回次に書かれていない表記を出すことになる。**
 * 許可リストは**両方の表記を別の名前として持つ**。
 *
 * ## 数えた回次の外には効かない（実測で判明した。これが一番大きい限界）
 *
 * **この表は「第195〜221回 ＋ 第142回」で実際に記録されていた名前である。**
 * **それ以外の回次では、正しい値でも止まる。**
 *
 * **これは机上の心配ではない。** **最初この表は第195〜221回（`data/` に在る 1,941 件）
 * だけから作った。** ところが**リポジトリに既に在った第142回（1998年）の fixture が
 * 即座に落ちた**——**参議院 `労働・社会政策`**（`keika/5516.htm`。生ページで確認）。
 * **2001 年の中央省庁再編の前は委員会の構成が違う。**
 *
 * **`docs/research/backfill-142-199.md` のとおり、第142〜199回は「取得できる」と確認済みの範囲で
 * あって、対象外ではない。** そこで**第142回 241 件も全数取得して表に入れた**——
 * **衆 25 / 参 18 種類が出て、その大半は現在の表に無い名前だった**
 * （`大蔵`・`逓信`・`国民福祉`・`商工`・`運輸`・`建設`…。2001 年の省庁再編の前後で別物）。
 * **第143〜194回・第199回は数えていない。**
 *
 * **だから `isKnownReferralCommittee` を回次で切る**（`referralAllowlistCoversSession`）。
 * **数えていない回次は「通す」のではなく「止める」**——
 * **allowlist の意味は「知らないものを通さない」ことであって、
 * 「数えていない範囲を黙って通す」ならただの denylist に戻る。**
 *
 * ## 塞げていない形（allowlist でも「付託先が正しい」の全証明にはならない）
 *
 * - **数えていない回次（第143〜194回・第199回）は、正しい値でも止まる**（上記）。
 *   **止まるので気づける**——**これは穴ではなく、気づく仕組みのほうである。**
 *   **穴は「数えた回次の表が、その回次については完全だ」という前提のほう**で、
 *   それは全数取得（失敗 0 件）に依っている。**取得が静かに失敗していれば表に穴が開く。**
 * - **許可リストに在る名前どうしの取り違えは止まらない。**
 *   `外務` を `総務` と読み違えても、どちらも衆の許可リストに在るので通る。
 *   **これを止められるのは欄の切り出し（`valueCell`）の正しさだけ**で、
 *   そちらは実ページとの突き合わせ（`docs/research/bill-referral.md` の 20 件 × 4 欄）で見ている。
 * - **同じ議案の中で欄をすり替える形も止まらない**（衆の本付託の値を衆の予備付託に入れる等）。
 *   どちらも同じ院の許可リストを通る。**欄の対応は `referralEntry` の呼び出し 4 行が唯一の根拠**で、
 *   そこは fixture（1DDEF5A: 予備 4/15・本 4/16）で日付が違うことを固定して守っている。
 * - **一次資料が新しい委員会を作ったら、正しい値でも止まる**（偽陽性）。
 *   **これは意図した振る舞いである**——**黙って推測を出すより、止まって人が数え直すほうがよい。**
 *   足すときは**実データを数えてから**にする（`docs/research/bill-referral.md` の 8 節）。
 * - **この表そのものが間違っていたら検査は間違いを守る。**
 *   だから表は**手で書かず、全数調査の出力から作った**上で、
 *   `bill-referral-allowlist.test.ts` が**数**と**実 fixture の全値が通ること**を固定している。
 * - **空欄・`審査省略` 系は、そもそもここに来ない**（`committee` にしないので）。
 *   ここが守るのは「付託先として出す値」だけである。
 * - **地方議会は対象外。** 島根は `総務委員会` と `委員会` 付きで記録しており、
 *   国会（`総務`）とは値の形が違う。**同じ表に混ぜない。**
 */

/**
 * **委員会の構成が変わった前後で表を分ける**（#1133）。
 *
 * **2001 年の中央省庁再編で委員会は別物になった。** 実測（第142回 1998年 と 第195〜221回）:
 *   衆 `大蔵` `商工` `逓信` `運輸` `建設` `厚生` `労働` `文教` `地方行政` `科学技術`
 *      → `財務金融` `経済産業` `国土交通` `厚生労働` `文部科学` `総務` …
 *   参 `国民福祉` `労働・社会政策` `交通・情報通信` `国土・環境` `地方行政・警察`
 *      → `厚生労働` `国土交通` `総務` …
 *
 * **1 つの表にまとめない。** まとめると **2026 年の議案に `大蔵` が入っても通ってしまう**
 * （実際にこのテストで捕まえた）。**その回次に記録されていた名前だけを通す。**
 */
interface ReferralEra {
  /**
   * **この表が根拠を持つ付託日の範囲**（両端を含む。ISO）。
   *
   * **回次ではなく日付で切る。** 理由は 2 つ:
   *   1. **議案の `session` は「提出回次」であって「付託された回次」ではない。**
   *      継続審議の議案は前の回次に提出されている（実例: `keika/5516.htm` は
   *      **提出回次 139 で、第142回の一覧に載り、平成10年に付託されている**）。
   *      提出回次で表を選ぶと、**数えた回次の議案なのに表が無い**という食い違いが出る。
   *   2. **委員会の構成は「時期」で変わる**（2001年の中央省庁再編）。日付のほうが素直である。
   *
   * **付託先のある欄には必ず日付がある**（実測: 2,759 欄すべて。日付の無い欄は
   * `審査省略` 系か空欄だけで、どちらも委員会名を出さない）。なので日付で引けないことは起きない。
   */
  readonly from: string;
  readonly to: string;
  /** この範囲を数えた出どころ（何を全数取得したか）。 */
  readonly countedFrom: string;
  readonly shugiin: readonly string[];
  readonly sangiin: readonly string[];
}

